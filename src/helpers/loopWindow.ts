/*
 * Круг — это не бесконечная лента. У прокрутки есть предел: браузер обрезает
 * её на десятках миллионов пикселей, а точность позиции и инерция плывут
 * задолго до того. Растить область бесконечно нельзя.
 *
 * Поэтому лента остаётся конечной, а по кругу её водит подмена позиции.
 * Контент повторяется через период, окно держим в средней копии, и как только
 * оно уходит за её границу — переносим позицию ровно на период. Прыжок не
 * виден: под окном в этот момент буквально тот же самый контент.
 */

/*
 * Сколько копий держать. Двух мало: из конца средней окно смотрит в
 * следующую, и та должна быть настоящей, а не пустотой за краем.
 */
export const loopCopies = (period: number, viewport: number) => {
  if (period <= 0) return 0;

  return Math.max(3, Math.ceil(viewport / period) + 2);
};

/*
 * Куда подменить позицию, чтобы окно вернулось в среднюю копию. `null` —
 * подменять не надо, окно и так там.
 *
 * Считаем по остатку, а не вычитанием одного периода: позицию может занести
 * далеко за раз — программным переходом или быстрым жестом, — и одного шага
 * тогда не хватит.
 */
export const loopShift = (position: number, period: number) => {
  if (period <= 0) return null;
  if (position >= period && position < period * 2) return null;

  const inside = (((position - period) % period) + period) % period;

  return period + inside;
};

/*
 * Страницы в круге обязаны делить оборот нацело. Иначе за последней страницей
 * оборот заканчивается не там, где она, — заворот приходится на середину, и
 * сетка страниц после него начинается со сдвигом: шаг вперёд и шаг назад
 * возвращают уже не туда, откуда пошли.
 *
 * Берём столько страниц, сколько нужно, что бы ни одна не оказалась длиннее
 * окна: страницы тогда чуть перекрываются, и ничего не пропущено. Обратное —
 * страницы длиннее окна — прятало бы полосу контента на каждом шаге.
 */
export const loopPages = (period: number, viewport: number, gap: number) => {
  const want = viewport + gap;

  if (period <= 0 || want <= 0) return { pages: 0, step: want };

  const pages = Math.max(1, Math.ceil(period / want));

  return { pages, step: period / pages };
};
